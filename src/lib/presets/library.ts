/**
 * Built-in preset library.
 *
 * Every preset is a partial adjustment set (Lightroom-style): only the fields
 * a look intends to change are present, so applying a preset leaves the rest
 * of the user's edit alone. Values are tuned for this renderer (see
 * engine/params.ts and engine/pixel.ts) and stay within schema RANGES.
 *
 * These are original interpretations of general photographic looks. Names
 * containing "-Inspired" describe a broad aesthetic and do not reproduce any
 * commercial film stock or preset pack.
 */
import type { PartialAdjustments } from '../schema/adjustments';

