export interface BuiltinPresetDefinition {
  /** 'builtin:<kebab-case slug of the name>' */
  id: string;
  name: string;
  category: PresetCategory;
  /** One plain sentence describing the look and when to use it. */
  description: string;
  /** 2-5 lowercase words. */
  tags: string[];
  adjustments: PartialAdjustments;
}

function slug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function preset(
  name: string,
  category: PresetCategory,
  description: string,
  tags: string[],
  adjustments: PartialAdjustments,
): BuiltinPresetDefinition {
  return { id: `builtin:${slug(name)}`, name, category, description, tags, adjustments };
}

