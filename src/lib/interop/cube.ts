/**
 * Adobe/Resolve .cube 3D LUT import and export.
 *
 * Export bakes only the per-pixel colour pipeline (white balance, exposure,
 * tone, HSL, grading, curves, levels, mixer). Spatial effects (clarity,
 * texture, dehaze, sharpening, noise reduction, vignette, grain), masks and
 * retouching cannot be represented in a LUT and are listed as omitted.
 */
import { deriveDevelopParams } from '../engine/params';
import { developPixel } from '../engine/pixel';
import type { Adjustments } from '../schema/adjustments';

export const MAX_CUBE_BYTES = 8 * 1024 * 1024;

export interface ParsedCube {
  title: string;
  size: number;
  /** size^3 * 3 floats, red fastest, normalised to 0..1. */
  data: Float32Array;
}

export function parseCube(text: string): ParsedCube {
  if (text.length > MAX_CUBE_BYTES) throw new Error('LUT file is larger than 8 MB.');
  let title = 'Imported LUT';
  let size = 0;
  let dmin = [0, 0, 0];
  let dmax = [1, 1, 1];
  const values: number[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const upper = line.toUpperCase();
    if (upper.startsWith('TITLE')) {
      title = line.replace(/^TITLE\s*/i, '').replace(/^"|"$/g, '').slice(0, 80) || title;
    } else if (upper.startsWith('LUT_1D_SIZE')) {
      throw new Error('1D LUTs are not supported. Use a 3D .cube LUT.');
    } else if (upper.startsWith('LUT_3D_SIZE')) {
      size = Number(line.split(/\s+/)[1]);
      if (!Number.isInteger(size) || size < 2 || size > 65) throw new Error('LUT size must be between 2 and 65.');
    } else if (upper.startsWith('DOMAIN_MIN')) {
      dmin = line.split(/\s+/).slice(1, 4).map(Number);
    } else if (upper.startsWith('DOMAIN_MAX')) {
      dmax = line.split(/\s+/).slice(1, 4).map(Number);
    } else if (/^[-+0-9.eE]/.test(line)) {
      const parts = line.split(/\s+/).map(Number);
      if (parts.length < 3 || parts.slice(0, 3).some((v) => !Number.isFinite(v))) throw new Error('The LUT contains invalid numbers.');
      values.push(parts[0], parts[1], parts[2]);
    } else {
      // Unknown keywords (e.g. LUT_IN_VIDEO_RANGE) are ignored but not executed.
    }
  }
  if (!size) throw new Error('Missing LUT_3D_SIZE. Is this a .cube file?');
  if (values.length !== size ** 3 * 3) throw new Error(`Expected ${size ** 3} entries, found ${values.length / 3}.`);
  if ([...dmin, ...dmax].some((v) => !Number.isFinite(v)) || dmax.some((v, i) => v <= dmin[i])) throw new Error('Invalid LUT domain.');
  const data = new Float32Array(values.length);
  for (let i = 0; i < values.length; i++) {
    const c = i % 3;
    data[i] = Math.min(1, Math.max(0, (values[i] - dmin[c]) / (dmax[c] - dmin[c])));
  }
  return { title, size, data };
}

export const CUBE_OMITTED = [
  'Texture, clarity, dehaze, sharpening and noise reduction (they depend on neighbouring pixels)',
  'Vignette and grain (they depend on pixel position)',
  'Masks, retouching, crop and rotation',
];

export function generateCube(adj: Adjustments, title: string, size = 33): string {
  const P = deriveDevelopParams(adj);
  const lines = [`TITLE "${title.replace(/"/g, "'").slice(0, 60)}"`, '# Generated by Lumen Atelier. Colour pipeline only.', `LUT_3D_SIZE ${size}`, 'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1'];
  for (let b = 0; b < size; b++)
    for (let g = 0; g < size; g++)
      for (let r = 0; r < size; r++) {
        const o = developPixel([r / (size - 1), g / (size - 1), b / (size - 1)], P);
        lines.push(`${o[0].toFixed(6)} ${o[1].toFixed(6)} ${o[2].toFixed(6)}`);
      }
  return `${lines.join('\n')}\n`;
}
